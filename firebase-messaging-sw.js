const messaging = firebase.messaging();

messaging.onBackgroundMessage((payload) => {
  console.log('[firebase-messaging-sw.js] Received background message:', payload);

  const notificationTitle = payload.data?.title || 'T&C News Hub';
  const notificationOptions = {
    body: payload.data?.body || 'New article update available!',
    icon: payload.data?.icon || '/news/android-chrome-192x192.png',
    badge: '/news/android-chrome-192x192.png',
    tag: 'tnc-news-wrapup', // Deduplicates notifications so only ONE card shows
    renotify: true,
    data: {
      url: payload.data?.url || '/news/'
    }
  };

  return self.registration.showNotification(notificationTitle, notificationOptions);
});

self.addEventListener('notificationclick', (event) => {
  event.notification.close();
  const urlToOpen = event.notification.data?.url || '/news/';

  event.waitUntil(
    clients.matchAll({ type: 'window', includeUncontrolled: true }).then((windowClients) => {
      for (let client of windowClients) {
        if (client.url === urlToOpen && 'focus' in client) {
          return client.focus();
        }
      }
      if (clients.openWindow) {
        return clients.openWindow(urlToOpen);
      }
    })
  );
});
